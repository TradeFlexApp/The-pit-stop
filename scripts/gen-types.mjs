// Regenerates src/types/supabase.ts from the LINKED Supabase project.
// Writes only when the CLI returns a real types file, so a failure (not linked,
// expired login) can never clobber the committed types.  Run: npm run db:types
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const isWin = process.platform === "win32";
let out = "";
try {
  out = execFileSync(isWin ? "npx.cmd" : "npx", ["supabase", "gen", "types", "typescript", "--remote", "--schema", "public"], {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
    shell: isWin,
  });
} catch {
  console.error("supabase gen types failed (is the project linked? run `npx supabase link`). src/types/supabase.ts left untouched.");
  process.exit(1);
}
if (!/export type Database\b/.test(out)) {
  console.error("Unexpected CLI output, nothing written:\n" + out.slice(0, 400));
  process.exit(1);
}
const header = `// GENERATED by \`npm run db:types\` from the linked Supabase project. Do not edit by hand.
// App-facing aliases live in src/types/database.ts.
`;
writeFileSync("src/types/supabase.ts", header + out);
console.log("wrote src/types/supabase.ts");
